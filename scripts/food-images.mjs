/**
 * Rebuilds src/data/foodImages.ts from the photos in assets/foods.
 * Name each photo after a food id from src/data/foods.ts (potato.jpg, cucumber.jpg, ...),
 * then run `npm run food-images`. `npm run food-images -- --missing` lists foods without a photo.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const ids = [...readFileSync('src/data/foods.ts', 'utf8').matchAll(/^  \['([a-z]+)', '/gm)].map((m) => m[1]);
const files = readdirSync('assets/foods').filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
const known = files.filter((f) => ids.includes(f.replace(/\.[^.]+$/, '')));
const unknown = files.filter((f) => !known.includes(f));

const lines = known.map((f) => `  ${f.replace(/\.[^.]+$/, '')}: require('@/assets/foods/${f}'),`);
writeFileSync(
  'src/data/foodImages.ts',
  `// Generated by scripts/food-images.mjs from assets/foods. Do not edit by hand.\n` +
    `export const FOOD_IMAGES: Record<string, number | string> = {\n${lines.join('\n')}${lines.length ? '\n' : ''}};\n`,
);

console.log(`${known.length} of ${ids.length} foods have a photo.`);
if (unknown.length) console.log(`Ignored (name is not a food id): ${unknown.join(', ')}`);
if (process.argv.includes('--missing')) {
  const have = new Set(known.map((f) => f.replace(/\.[^.]+$/, '')));
  console.log(`Missing: ${ids.filter((id) => !have.has(id)).join(', ')}`);
}
